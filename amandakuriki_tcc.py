"""# 1.2. Adicionando os tempos de processamento aos pontos adicionados

- Apenas clusterização (sem P-Mediana/P-Centro/Capacitado)

base da ambulância = centroide geométrico do cluster

- Distância: será calculada via OSRM (rota real de carro), não Haversine.
- O tempo T3 (deslocamento base -> ocorrência) NÃO é calculado nesta seção,
  porque ele depende dos CENTROS DE CLUSTER, que só existem depois da
  clusterização (Seção 2) e do cálculo de distância via OSRM (Seção 3).
  Aqui geramos apenas T1, T2, T4, T5 (tempos que não dependem da posição
  da base), exatamente como no notebook original -- T3 será somado ao
  Total_Time somente na Seção 3, corrigindo a lacuna identificada no
  notebook de referência.
"""

import numpy as np
import pandas as pd
import random
from enum import Enum
from typing import List, Tuple
from shapely.geometry import Point
import matplotlib.pyplot as plt
import seaborn as sns

class DistKind(Enum):
    EXPONENTIAL = 'exponential'
    NORMAL = 'normal'
    LOGNORMAL = 'lognormal'

def generate_time_value(dist_kind, p1, p2, p3):
    """
    Gera um único valor de tempo, de acordo com a distribuição escolhida.
    p1, p2, p3 são os parâmetros daquela distribuição.
    """
    if dist_kind == DistKind.EXPONENTIAL:
        return np.random.exponential(scale=p1)
    elif dist_kind == DistKind.NORMAL:
        return np.random.normal(loc=p1, scale=p2)
    elif dist_kind == DistKind.LOGNORMAL:
        return np.random.lognormal(mean=p1, sigma=p2)
    else:
        raise ValueError(f"Distribuição desconhecida: {dist_kind}")

def generate_occurrences(
    city_row: pd.Series,
    n: int,
    city_geometry: 'Polygon',
    dist_t1: DistKind, t1_p1: float, t1_p2: float, t1_p3: float,
    dist_t2: DistKind, t2_p1: float, t2_p2: float, t2_p3: float,
    dist_t4: DistKind, t4_p1: float, t4_p2: float, t4_p3: float,
    dist_t5: DistKind, t5_p1: float, t5_p2: float, t5_p3: float,
    existing_pts: List[Tuple[float, float]] = None,
    seed: int = None,
    seed_tempos: int = None,
) -> pd.DataFrame:
    """
    Gera um DataFrame de ocorrências com os tempos de processamento simulados
    (T1, T2, T4, T5). O T3 (deslocamento) NÃO é gerado aqui -- ele depende
    do centro de cluster, calculado somente na Seção 2/3.
    """
    if existing_pts:
        points = existing_pts
    else:
        if seed is not None:
            random.seed(seed)
        minx, miny, maxx, maxy = city_geometry.bounds
        points = []
        while len(points) < n:
            x = random.uniform(minx, maxx)
            y = random.uniform(miny, maxy)
            p = Point(x, y)
            if city_geometry.contains(p):
                points.append((y, x))

    if seed_tempos is not None:
      np.random.seed(seed_tempos)

    data = []
    for i, (lat, lon) in enumerate(points):
        t1 = generate_time_value(dist_t1, t1_p1, t1_p2, t1_p3)
        t2 = generate_time_value(dist_t2, t2_p1, t2_p2, t2_p3)
        t4 = generate_time_value(dist_t4, t4_p1, t4_p2, t4_p3)
        t5 = generate_time_value(dist_t5, t5_p1, t5_p2, t5_p3)
        data.append({
            'ID': f"{city_row['municipio_nome']}-{i:04d}",
            'lat': lat,
            'lon': lon,
            'T1': t1,
            'T2': t2,
            'T4': t4,
            'T5': t5,
            'municipio_nome': city_row['municipio_nome'],
            'Populacao_2022': city_row.get('Populacao_2022', None),
        })
    return pd.DataFrame(data)

def create_occurrence_table_from_points(
    input_pontos: List[Tuple[float, float]],
    city_info: pd.Series,
    t1_dist=DistKind.EXPONENTIAL, t1_p1=5.0, t1_p2=0.0, t1_p3=0.0,
    t2_dist=DistKind.NORMAL, t2_p1=2.0, t2_p2=0.5, t2_p3=0.0,
    t4_dist=DistKind.NORMAL, t4_p1=10.0, t4_p2=3.0, t4_p3=0.0,
    t5_dist=DistKind.LOGNORMAL, t5_p1=2.3, t5_p2=0.5, t5_p3=0.0,
    seed_tempos: int = None,
) -> pd.DataFrame:
    """
    Cria a tabela de ocorrências a partir da lista de pontos de Campinas
    gerada na Seção 1.1, adicionando os tempos T1, T2, T4, T5 simulados.
    """
    if 'Populacao_2022' not in city_info:
        city_info = city_info.copy()
        city_info['Populacao_2022'] = None
    return generate_occurrences(
        city_row=city_info,
        n=len(input_pontos),
        city_geometry=city_info['geometry'],
        dist_t1=t1_dist, t1_p1=t1_p1, t1_p2=t1_p2, t1_p3=t1_p3,
        dist_t2=t2_dist, t2_p1=t2_p1, t2_p2=t2_p2, t2_p3=t2_p3,
        dist_t4=t4_dist, t4_p1=t4_p1, t4_p2=t4_p2, t4_p3=t4_p3,
        dist_t5=t5_dist, t5_p1=t5_p1, t5_p2=t5_p2, t5_p3=t5_p3,
        existing_pts=input_pontos,
        seed_tempos=seed_tempos,
    )

