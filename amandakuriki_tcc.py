"""## 7.2. Funções de apoio: aplicar a configuração e calcular o Silhouette"""

"""
As funções abaixo seguem o mesmo padrão de aplicar_kmeans() (Seção 2) e de
aplicar_agglomerative() (Seção 5), mas recebem os hiperparâmetros que o Optuna vai
testar. Com os valores da Seção 2 (init='k-means++', n_init=10, random_state=42), o
resultado do K-Means é idêntico ao de aplicar_kmeans().

O Silhouette é SEMPRE calculado com a distância euclidiana (padrão do scikit-learn)
sobre as coordenadas (Latitude, Longitude), para que os dois métodos sejam comparados
com a mesma régua, mesmo quando o Agglomerative agrupa com a métrica 'manhattan'.
"""


def aplicar_kmeans_opt(df_ocorrencias: pd.DataFrame, n_clusters: int,
                       coluna_cluster: str, init: str = 'k-means++',
                       n_init: int = 10, random_state: int = 42):
    """
    Aplica o K-Means com os hiperparâmetros informados.
    Retorna (df_com_cluster, centers_dict), no mesmo formato de aplicar_kmeans().
    """
    df_com_cluster = df_ocorrencias.rename(
        columns={'lat': 'Latitude', 'lon': 'Longitude'}
    ).copy()
    X = df_com_cluster.loc[:, ['Latitude', 'Longitude']].values
    modelo = KMeans(
        n_clusters=n_clusters,
        init=init,
        n_init=n_init,
        random_state=random_state,
    )
    rotulos = modelo.fit_predict(X)
    df_com_cluster[coluna_cluster] = rotulos + 1
    centers_dict = {
        str(i + 1): modelo.cluster_centers_[i]
        for i in range(n_clusters)
    }
    return df_com_cluster, centers_dict


def aplicar_agglomerative_opt(df_ocorrencias: pd.DataFrame, n_clusters: int,
                              coluna_cluster: str, linkage: str = 'ward',
                              metric: str = 'euclidean'):
    """
    Aplica o Agglomerative Clustering com linkage e métrica informados.
    Retorna (df_com_cluster, centers_dict), no mesmo formato de aplicar_agglomerative().
    O centroide é a média das coordenadas de cada cluster (Seção 5).
    """
    df_com_cluster = df_ocorrencias.rename(
        columns={'lat': 'Latitude', 'lon': 'Longitude'}
    ).copy()
    X = df_com_cluster.loc[:, ['Latitude', 'Longitude']].values
    modelo = AgglomerativeClustering(
        n_clusters=n_clusters,
        linkage=linkage,
        metric=metric,
    )
    rotulos = modelo.fit_predict(X)
    df_com_cluster[coluna_cluster] = rotulos + 1
    centers_dict = calcular_centroides_por_cluster(df_com_cluster, coluna_cluster)
    return df_com_cluster, centers_dict


def calcular_silhouette(df_com_cluster: pd.DataFrame, coluna_cluster: str) -> float:
    """
    Silhouette Score (distância euclidiana) sobre TODAS as ocorrências.
    Devolve -1.0 se houver menos de 2 clusters (configuração inválida).
    """
    X = df_com_cluster.loc[:, ['Latitude', 'Longitude']].values
    rotulos = df_com_cluster[coluna_cluster].values
    if len(np.unique(rotulos)) < 2:
        return -1.0
    return float(silhouette_score(X, rotulos))

"""## 7.3. Funções objetivo (uma por método)"""

"""

Cada função recebe um trial, sorteia os hiperparâmetros daquele método, aplica a
clusterização e devolve o Silhouette Score (que o Optuna vai MAXIMIZAR). O espaço de
busca do Agglomerative é condicional: com linkage='ward', a métrica não é sorteada e
fica fixa em 'euclidean'.
"""


def objective_kmeans(trial: optuna.Trial) -> float:
    k = trial.suggest_int('n_clusters', K_MIN_OPT, K_MAX_OPT)
    init = trial.suggest_categorical('init', INIT_OPT)
    n_init = trial.suggest_categorical('n_init', N_INIT_OPT)

    coluna = f'kmeans{k}'
    df_cl, _ = aplicar_kmeans_opt(df_ocorrencias_campinas, n_clusters=k,
                                  coluna_cluster=coluna, init=init, n_init=n_init,
                                  random_state=RANDOM_STATE)
    return calcular_silhouette(df_cl, coluna)


def objective_agglomerative(trial: optuna.Trial) -> float:
    k = trial.suggest_int('n_clusters', K_MIN_OPT, K_MAX_OPT)
    linkage = trial.suggest_categorical('linkage', LINKAGE_OPT)
    if linkage == 'ward':
        metric = 'euclidean'          # Ward só aceita a métrica euclidiana (não é sorteada)
    else:
        metric = trial.suggest_categorical('metric', METRICA_OPT)
    trial.set_user_attr('metric', metric)   # guarda a métrica usada (inclusive no Ward)

    coluna = f'agglomerative{k}'
    df_cl, _ = aplicar_agglomerative_opt(df_ocorrencias_campinas, n_clusters=k,
                                         coluna_cluster=coluna, linkage=linkage,
                                         metric=metric)
    return calcular_silhouette(df_cl, coluna)

