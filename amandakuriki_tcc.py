"""# 5. Cálculo dos clusters - Agglomerative Clustering para k=5

- O AgglomerativeClustering do scikit-learn NÃO calcula um centro de cluster nativamente (não existe atributo cluster_centers_, ao contrário do KMeans). Isso é coerente com a lógica hierárquica do algoritmo - o processo de fusão (linkage='ward') nunca usa a noção de "centro fixo", ele trabalha com variância entre pontos.

  - Por isso, esta seção inclui uma função auxiliar calcular_centroides_por_cluster() que calcula manualmente a média aritmética das coordenadas (Latitude, Longitude) de cada cluster após a atribuição de rótulos - exatamente a mesma definição de "base = centroide geométrico do cluster" já usada para o K-Means, só que obtida por um caminho diferente.

- k=5 mantido igual ao Passo 1 (K-Means) de propósito, para permitir uma
comparação direta e justa entre os dois métodos sobre o MESMO valor de
k e o MESMO conjunto de ocorrências (df_ocorrencias_campinas).

## 5.1. Aplicação do Agglomerative Clustering
"""

import numpy as np
import pandas as pd
from sklearn.cluster import AgglomerativeClustering

MODEL_NAME_AGG = 'agglomerative'
N_CLUSTERS_AGG = 5  # mesmo k do Passo 1 (K-Means), para comparação direta
LINKAGE_AGG = 'ward'  # ver material de apoio: 'ward' é o critério recomendado
                       # para este TCC (dados sem formato não-convexo conhecido)
COLUNA_CLUSTER_AGG = f'{MODEL_NAME_AGG}{N_CLUSTERS_AGG}'


def calcular_centroides_por_cluster(df_com_cluster: pd.DataFrame,
                                     coluna_cluster: str) -> dict:
    """
    Calcula manualmente o centroide (média aritmética de Latitude e
    Longitude) de cada cluster -- necessário porque o
    AgglomerativeClustering, ao contrário do KMeans, não fornece esse
    valor nativamente (sem atributo cluster_centers_).

    Retorna um dicionário no MESMO formato usado pelo KMeans no Passo 1
    (centers_dict = {'1': [lat, lon], '2': [lat, lon], ...}), para que
    as funções de mapa já existentes (create_map, create_polygons etc.)
    possam ser reaproveitadas sem nenhuma alteração.
    """
    centers_dict = {}
    for cluster_id in sorted(df_com_cluster[coluna_cluster].unique()):
        pontos_cluster = df_com_cluster[
            df_com_cluster[coluna_cluster] == cluster_id
        ][['Latitude', 'Longitude']]
        centro_lat = pontos_cluster['Latitude'].mean()
        centro_lon = pontos_cluster['Longitude'].mean()
        centers_dict[str(int(cluster_id))] = np.array([centro_lat, centro_lon])
    return centers_dict


def aplicar_agglomerative(df_ocorrencias: pd.DataFrame, n_clusters: int,
                           coluna_cluster: str, linkage: str = 'ward'):
    """
    Aplica o Agglomerative Clustering sobre as coordenadas (lat, lon)
    das ocorrências.

    Retorna:
        df_com_cluster : cópia do DataFrame de entrada, com colunas
                          novas: 'Latitude'/'Longitude' (renomeadas de
                          lat/lon) e o rótulo do cluster (na coluna
                          indicada por 'coluna_cluster', numerado a
                          partir de 1 -- mesma convenção do K-Means).
        centers_dict    : dicionário {'1': [lat, lon], '2': [lat, lon], ...}
                          com o centroide de cada cluster, calculado
                          manualmente (ver calcular_centroides_por_cluster).
                          É este centroide que representa a base de
                          ambulância alocada para aquele grupo.

    Nota: diferente do KMeans, o AgglomerativeClustering não aceita
    random_state -- o algoritmo é DETERMINÍSTICO (sempre produz o mesmo
    resultado para os mesmos dados e mesmo linkage), então não há
    necessidade de fixar uma semente aqui.
    """
    df_com_cluster = df_ocorrencias.rename(
        columns={'lat': 'Latitude', 'lon': 'Longitude'}
    ).copy()

    X = df_com_cluster.loc[:, ['Latitude', 'Longitude']].values

    modelo = AgglomerativeClustering(
        n_clusters=n_clusters,
        linkage=linkage,
    )
    rotulos = modelo.fit_predict(X)

    df_com_cluster[coluna_cluster] = rotulos + 1

    centers_dict = calcular_centroides_por_cluster(df_com_cluster, coluna_cluster)

    return df_com_cluster, centers_dict


