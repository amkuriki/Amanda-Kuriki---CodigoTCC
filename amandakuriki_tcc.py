def gerar_grid_mapas_k(df_ocorrencias: pd.DataFrame, k_values: list,
                        random_state: int = 42, n_colunas: int = 3):
    """
    Para cada valor de k em k_values:
        1. Roda o K-Means (rápido, sem OSRM)
        2. Desenha um mapa ESTÁTICO (matplotlib) com os pontos coloridos
           por cluster, o polígono de área (ConvexHull, se houver >= 3
           pontos) e um marcador '^' no centroide de cada cluster.
    Todos os mapas são organizados lado a lado num grid, para facilitar
    a comparação visual direta entre diferentes valores de k.
    """
    lat_col = 'lat' if 'lat' in df_ocorrencias.columns else 'Latitude'
    lon_col = 'lon' if 'lon' in df_ocorrencias.columns else 'Longitude'
    X = df_ocorrencias.loc[:, [lat_col, lon_col]].values

    n_k = len(k_values)
    n_linhas = int(np.ceil(n_k / n_colunas))

    fig, axes = plt.subplots(n_linhas, n_colunas,
                              figsize=(5.5 * n_colunas, 5.5 * n_linhas))
    axes = np.array(axes).reshape(-1)  # achata em 1D, mesmo se só 1 linha

    for idx, k in enumerate(k_values):
        ax = axes[idx]
        modelo = KMeans(n_clusters=k, init='k-means++', n_init=10, random_state=random_state)
        rotulos = modelo.fit_predict(X) + 1  # 1 a k, por consistência com o resto do TCC

        for cluster_id in range(1, k + 1):
            pontos_cluster = X[rotulos == cluster_id]
            cor = cor_matplotlib(cluster_id)

            ax.scatter(pontos_cluster[:, 1], pontos_cluster[:, 0],
                       color=cor, s=25, alpha=0.75, edgecolor='none')

