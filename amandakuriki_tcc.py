def calculate_confidence_interval(data, confidence: float = 0.95):
    """
    Calcula o intervalo de confiança (padrão: 95%) para a média de uma
    amostra, usando a distribuição t de Student (apropriada quando o
    desvio padrão populacional é desconhecido).
    """
    data = [d for d in data if not pd.isna(d)]
    if len(data) < 2:
        return float('nan'), float('nan')
    mean = np.mean(data)
    std_err = stats.sem(data)
    n = len(data)
    h = std_err * stats.t.ppf((1 + confidence) / 2., n - 1)
    return mean - h, mean + h

