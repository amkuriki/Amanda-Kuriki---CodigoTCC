def gerar_pontos_no_poligono(poligono, n_pontos=500, seed=0):
    """
    Gera 'n_pontos' pontos aleatórios uniformemente distribuídos
    dentro de um polígono, usando rejection sampling:
    sorteia pontos dentro do bounding box e só aceita os que
    caem de fato dentro do polígono real.
    """
    random.seed(seed)
    minx, miny, maxx, maxy = poligono.bounds
    pontos = []
    while len(pontos) < n_pontos:
        x = random.uniform(minx, maxx)
        y = random.uniform(miny, maxy)
        ponto = Point(x, y)
        if poligono.contains(ponto):
            pontos.append((y, x))  # (lat, lon)
    return pontos

