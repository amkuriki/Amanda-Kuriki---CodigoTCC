# execução -- útil mais adiante, na Seção 7 (Optuna), que reaproveita as rotas do baseline.
CACHE_ROTAS = {}

def get_route(origem, destino):
    """
    Consulta o OSRM público e retorna a rota real de carro entre dois
    pontos (origem e destino), cada um no formato [lat, lon].

    Retorna um dicionário com:
        route        : lista de pontos [lat, lon] representando o
                        traçado da rota (decodificado do polyline)
        start_point   : [lat, lon] do ponto de partida confirmado pelo OSRM
        end_point     : [lat, lon] do ponto de chegada confirmado pelo OSRM
        distance      : distância da rota, em km

    Em caso de falha (após esgotar as tentativas), retorna None -- quem
    chamar esta função deve tratar esse caso (ver uso mais abaixo).
    """
    chave_cache = (round(origem[0], 6), round(origem[1], 6),
                   round(destino[0], 6), round(destino[1], 6))
    if chave_cache in CACHE_ROTAS:
        return CACHE_ROTAS[chave_cache]
    pickup_lon, pickup_lat = origem[1], origem[0]
    dropoff_lon, dropoff_lat = destino[1], destino[0]
    loc = f"{pickup_lon},{pickup_lat};{dropoff_lon},{dropoff_lat}"
    for tentativa in range(1, MAX_TENTATIVAS + 1):
        try:
            r = requests.get(OSRM_URL + loc, timeout=TIMEOUT_SEGUNDOS)
            if r.status_code != 200:
                raise ValueError(f"status_code={r.status_code}")
            res = r.json()
            if "routes" not in res or len(res["routes"]) == 0:
                raise ValueError("resposta sem 'routes'")
            rota_geometria = polyline.decode(res["routes"][0]["geometry"])
            start_point = [res["waypoints"][0]["location"][1],
                           res["waypoints"][0]["location"][0]]
            end_point = [res["waypoints"][1]["location"][1],
                         res["waypoints"][1]["location"][0]]
            distancia_km = res["routes"][0]["distance"] / 1000
            resultado = {
                "route": rota_geometria,
                "start_point": start_point,
                "end_point": end_point,
                "distance": distancia_km,
            }
            CACHE_ROTAS[chave_cache] = resultado
            return resultado
        except Exception as e:
            if tentativa < MAX_TENTATIVAS:
                time.sleep(PAUSA_ENTRE_TENTATIVAS)
            else:
                print(f"[Aviso] Falha ao obter rota OSRM "
                      f"(origem={origem}, destino={destino}) "
                      f"após {MAX_TENTATIVAS} tentativas: {e}")
                return None

def get_dist_paths_centers(df_accidents: pd.DataFrame, coluna_cluster: str,
                            centers_dict: dict):
    """
    Para cada cluster, calcula a rota/distância (via OSRM) do centro
    (base) até cada ocorrência pertencente àquele cluster.

    Retorna:
        vD_log_e1   : dict {cluster_id_str: [distancias em km, uma por
                       ocorrência daquele cluster]}
        vD_route_e1 : dict {cluster_id_str: [rotas (lista de pontos),
                       uma por ocorrência daquele cluster]}
    """
    vD_log_e1 = {}
    vD_route_e1 = {}
    for g in np.sort(df_accidents[coluna_cluster].unique()):
        g = int(g)
        origem = centers_dict[str(g)]  # [lat, lon] do centroide
        destino_df = df_accidents[
            df_accidents[coluna_cluster] == g
        ].loc[:, ['Latitude', 'Longitude']]
        distancias = []
        rotas = []
        for _, row in destino_df.iterrows():
            destino = [row['Latitude'], row['Longitude']]
            resultado = get_route(origem, destino)
            if resultado is not None:
                distancias.append(resultado['distance'])
                rotas.append(resultado['route'])
            else:
                # Falha pontual: registra NaN em vez de descartar a
                # ocorrência inteira da análise.
                distancias.append(np.nan)
                rotas.append(None)
        vD_log_e1[str(g)] = distancias
        vD_route_e1[str(g)] = rotas
    return vD_log_e1, vD_route_e1

