from sklearn.cluster import KMeans

MODEL_NAME = 'kmeans'
N_CLUSTERS = 5
RANDOM_STATE = 42
COLUNA_CLUSTER = f'{MODEL_NAME}{N_CLUSTERS}'

def aplicar_kmeans(df_ocorrencias: pd.DataFrame, n_clusters: int,
                    coluna_cluster: str, random_state: int = 42):
    """
    Aplica o K-Means sobre as coordenadas (lat, lon) das ocorrências.
    """
    df_com_cluster = df_ocorrencias.rename(
        columns={'lat': 'Latitude', 'lon': 'Longitude'}
    ).copy()
    X = df_com_cluster.loc[:, ['Latitude', 'Longitude']].values
    modelo = KMeans(
        n_clusters=n_clusters,
        init='k-means++',
        n_init=10,
        random_state=random_state,
    )
    rotulos = modelo.fit_predict(X)
    df_com_cluster[coluna_cluster] = rotulos + 1
    centers_dict = {
        str(i + 1): modelo.cluster_centers_[i]
        for i in range(n_clusters)
    }
    return df_com_cluster, centers_dict

df_accidents, centers_dict = aplicar_kmeans(
    df_ocorrencias_campinas,
    n_clusters=N_CLUSTERS,
    coluna_cluster=COLUNA_CLUSTER,
    random_state=RANDOM_STATE,
)

print(f"K-Means aplicado com k={N_CLUSTERS} (Campinas)")
print(f"Coluna de cluster criada: '{COLUNA_CLUSTER}'")
print("\nCentros dos clusters (base de ambulância = centroide):")
