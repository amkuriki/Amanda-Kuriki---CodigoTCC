"""
Critério de desempate: se mais de um trial atingir o mesmo Silhouette máximo (o que
pode acontecer, pois hiperparâmetros diferentes podem gerar a mesma partição), escolhe-se,
pela ordem: o menor k; depois, a configuração mais próxima da usada nas seções anteriores
(K-Means: init='k-means++' e n_init=10; Agglomerative: linkage='ward' e metric='euclidean');
por fim, o trial de menor número.
"""


def tabela_trials(estudo: optuna.Study, metodo: str) -> pd.DataFrame:
    """Uma linha por trial concluído, ordenada do maior para o menor Silhouette."""
    linhas = []
    for t in estudo.trials:
        if t.state != optuna.trial.TrialState.COMPLETE:
            continue
        if metodo == 'kmeans':
            linhas.append({'trial': t.number, 'k': t.params['n_clusters'],
                           'init': t.params['init'], 'n_init': t.params['n_init'],
                           'silhouette': t.value})
        else:
            linhas.append({'trial': t.number, 'k': t.params['n_clusters'],
                           'linkage': t.params['linkage'],
                           'metric': t.user_attrs['metric'],
                           'silhouette': t.value})
    return (pd.DataFrame(linhas)
            .sort_values(['silhouette', 'trial'], ascending=[False, True])
            .reset_index(drop=True))


def selecionar_melhor_trial(estudo: optuna.Study, metodo: str):
    """
    Devolve (melhor_trial, n_empatados): o trial de maior Silhouette, aplicando o
    critério de desempate descrito acima.
    """
    completos = [t for t in estudo.trials if t.state == optuna.trial.TrialState.COMPLETE]
    maior = max(t.value for t in completos)
    empatados = [t for t in completos if maior - t.value < 1e-9]

    def chave(t):
        if metodo == 'kmeans':
            return (t.params['n_clusters'], t.params['init'] != 'k-means++',
                    abs(t.params['n_init'] - 10), t.number)
        return (t.params['n_clusters'], t.params['linkage'] != 'ward',
                t.user_attrs['metric'] != 'euclidean', t.number)

    return sorted(empatados, key=chave)[0], len(empatados)


def hiperparametros_do_trial(trial: optuna.trial.FrozenTrial, metodo: str) -> dict:
    """Hiperparâmetros completos do trial (inclui a métrica do Ward)."""
    hp = {'n_clusters': trial.params['n_clusters']}
    if metodo == 'kmeans':
        hp.update({'init': trial.params['init'], 'n_init': trial.params['n_init']})
    else:
        hp.update({'linkage': trial.params['linkage'],
                   'metric': trial.user_attrs['metric']})
    return hp


def descrever_hiperparametros(metodo: str, hp: dict) -> str:
    if metodo == 'kmeans':
        return f"k={hp['n_clusters']}, init={hp['init']}, n_init={hp['n_init']}"
    return f"k={hp['n_clusters']}, linkage={hp['linkage']}, metric={hp['metric']}"


