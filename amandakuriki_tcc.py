def cor_do_cluster(cluster_id: int) -> str:
    return CORES_DISPONIVEIS[(cluster_id - 1) % len(CORES_DISPONIVEIS)]

def create_map(df_accidents: pd.DataFrame, zoom_start: int = 11) -> folium.Map:
    center_lat = df_accidents['Latitude'].mean()
    center_lon = df_accidents['Longitude'].mean()
    map_osm = folium.Map(
        location=[center_lat, center_lon],
        tiles=CARTO_TILES,
        attr=CARTO_ATTR,
        zoom_start=zoom_start,
    )
    min_lat, max_lat = df_accidents['Latitude'].min(), df_accidents['Latitude'].max()
    min_lon, max_lon = df_accidents['Longitude'].min(), df_accidents['Longitude'].max()
    map_osm.fit_bounds([[min_lat, min_lon], [max_lat, max_lon]])
    return map_osm

def draw_points_clustered(map_osm: folium.Map, df_accidents: pd.DataFrame,
                           coluna_cluster: str) -> folium.Map:
    fgc_dict = {}
    for cluster in np.sort(df_accidents[coluna_cluster].unique()):
        fgc_dict[str(cluster)] = folium.FeatureGroup(name=f'Pontos - Cluster {cluster}')
        map_osm.add_child(fgc_dict[str(cluster)])
    for _, row in df_accidents.iterrows():
        cluster = int(row[coluna_cluster])
        folium.CircleMarker(
            location=[row['Latitude'], row['Longitude']],
            radius=5,
            fill_color=cor_do_cluster(cluster),
            color=cor_do_cluster(cluster),
            fill_opacity=0.8,
            popup=f'Cluster {cluster}<br>ID: {row["ID"]}',
        ).add_to(fgc_dict[str(cluster)])
    return map_osm

def create_polygons(map_osm: folium.Map, df_accidents: pd.DataFrame,
                     coluna_cluster: str, centers_dict: dict) -> folium.Map:
    for g in np.sort(df_accidents[coluna_cluster].unique()):
        g = int(g)
        latlon_cut = df_accidents[
            df_accidents[coluna_cluster] == g
        ].loc[:, ['Latitude', 'Longitude']]
        if len(latlon_cut) >= 3:
            try:
                hull = ConvexHull(latlon_cut.values)
                lat_hull = latlon_cut.values[hull.vertices, 0]
                lon_hull = latlon_cut.values[hull.vertices, 1]
                area = list(zip(lat_hull, lon_hull))
                poligono_fg = folium.FeatureGroup(
                    name=f'<u><b>Área {g}</b></u>', show=True
                )
                folium.Polygon(
                    locations=area,
                    color=cor_do_cluster(g),
                    weight=2,
                    fill=True,
                    fill_opacity=0.1,
                    opacity=0.8,
                ).add_to(poligono_fg)
                map_osm.add_child(poligono_fg)
            except Exception as e:
                print(f"[Aviso] Não foi possível gerar o polígono do "
                      f"cluster {g} ({len(latlon_cut)} pontos): {e}")
        else:
            print(f"[Aviso] Cluster {g} tem apenas {len(latlon_cut)} "
                  f"ponto(s) -- polígono de área não desenhado "
                  f"(ConvexHull exige >= 3 pontos).")
        center_fg = folium.FeatureGroup(
            name=f'<u><b>Centro {g}</b></u>', show=True
        )
        default_icon = folium.Icon(
            color=cor_do_cluster(g), icon='ambulance', prefix='fa'
        )
        lat_centro = centers_dict[str(g)][0]
        lon_centro = centers_dict[str(g)][1]
        folium.Marker(
            location=[lat_centro, lon_centro],
            popup=f'Base do Cluster {g} ({len(latlon_cut)} ocorrências)',
            icon=default_icon,
        ).add_to(center_fg)
        map_osm.add_child(center_fg)
    return map_osm

