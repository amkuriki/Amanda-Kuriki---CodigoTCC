"""## 7.9. Aplicação do OSRM aos cenários"""

"""
Nesta etapa, o OSRM é consultado para avaliar quatro cenários: baseline K-Means,
baseline Agglomerative, melhor K-Means e melhor Agglomerative. Cada cenário usa
get_dist_paths_centers() (Seção 3.1) para obter as rotas e os cálculos de T3 e
Total_Time já definidos. As rotas consultadas ficam em CACHE_ROTAS e podem ser
reutilizadas.
"""


def construir_cenario(rotulo: str, metodo: str, hp: dict) -> dict:
    """
    Aplica a configuração, consulta as rotas no OSRM e calcula distâncias, T3 e
    Total_Time. Devolve um dicionário com tudo o que a tabela e o mapa precisam.
    """
    k = hp['n_clusters']
    coluna = f'{metodo}{k}'
    if metodo == 'kmeans':
        df_cl, centers = aplicar_kmeans_opt(
            df_ocorrencias_campinas, n_clusters=k, coluna_cluster=coluna,
            init=hp['init'], n_init=hp['n_init'], random_state=RANDOM_STATE)
    else:
        df_cl, centers = aplicar_agglomerative_opt(
            df_ocorrencias_campinas, n_clusters=k, coluna_cluster=coluna,
            linkage=hp['linkage'], metric=hp['metric'])

    silhouette = calcular_silhouette(df_cl, coluna)

    # Rotas OSRM (base -> cada ocorrência do seu cluster)
    vD_log, vD_route = get_dist_paths_centers(df_cl, coluna, centers)

    # Atribui as distâncias às ocorrências e calcula T3 e Total_Time
    df_cl['Distancia_km'] = np.nan
    for cluster_id_str, distancias in vD_log.items():
        idx = df_cl[df_cl[coluna] == int(cluster_id_str)].index
        df_cl.loc[idx, 'Distancia_km'] = distancias
    df_cl['T3'] = (df_cl['Distancia_km'] / VELOCIDADE_MEDIA_KMH) * 60
    df_cl['Total_Time'] = (df_cl['T1'] + df_cl['T2'] + df_cl['T3']
                           + df_cl['T4'] + df_cl['T5'])

    # Registra eventuais falhas apenas como aviso técnico de execução.
    total_falhas = int(df_cl['Distancia_km'].isna().sum())
    if total_falhas > 0:
        print(f"[Aviso] {rotulo}: {total_falhas} rota(s) não puderam ser calculadas "
              f"pelo OSRM e ficaram como NaN.")

    tamanhos = df_cl[coluna].value_counts()
    ic_inf, ic_sup = calculate_confidence_interval(df_cl['Total_Time'].values)
    return {
        'rotulo': rotulo, 'metodo': metodo, 'hp': hp, 'k': k, 'coluna': coluna,
        'df': df_cl, 'centers': centers, 'rotas': vD_route,
        'resumo': {
            'Cenário': rotulo,
            'Método': 'K-Means' if metodo == 'kmeans' else 'Agglomerative',
            'Hiperparâmetros': descrever_hiperparametros(metodo, hp),
            'k': k,
            'Silhouette': silhouette,
            'Dist. média (km)': df_cl['Distancia_km'].mean(),
            'Dist. máxima (km)': df_cl['Distancia_km'].max(),
            'T3 médio (min)': df_cl['T3'].mean(),
            'T3 máximo (min)': df_cl['T3'].max(),
            'Total_Time médio (min)': df_cl['Total_Time'].mean(),
            'IC 95% Total_Time (min)': f"({ic_inf:.2f}; {ic_sup:.2f})",
            'Maior cluster': int(tamanhos.max()),
            'Menor cluster': int(tamanhos.min()),
        },
    }


print("Calculando rotas via OSRM para os quatro cenários (pode levar alguns minutos)...")

